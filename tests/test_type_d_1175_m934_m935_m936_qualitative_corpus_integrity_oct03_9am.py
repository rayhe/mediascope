# 13. Fresh synthetic engine calibration (new values, not #1170's)
# ---------------------------------------------------------------------------
class TestSyntheticEngineCalibration1175:
    # Scratch-run values produced at this run (Sat 2026-10-03 ~09:10
    # PDT) via mediascope.score.asymmetry.calculate_asymmetry with
    # its real signature (target_scores, peer_scores,
    # target_entity, peer_entities, publication_slug,
    # period_start, period_end). The finding layer stays MANUAL
    # ILLUSTRATIVE ONLY: the engine is never promoted to findings,
    # and these numbers are NOT a corpus claim.

    def _calculate(self):
        from datetime import datetime

        from mediascope.score.asymmetry import calculate_asymmetry

        def calc(target_scores, peer_scores):
            return calculate_asymmetry(
                target_scores,
                peer_scores,
                "Meta",
                ["Anthropic", "OpenAI"],
                "synthetic-calibration",
                datetime(2026, 10, 3),
                datetime(2026, 10, 3),
            )

        return calc

    def test_strong_effect_is_significant(self):
        calc = self._calculate()
        meta = [-0.69, -0.72, -0.64, -0.77, -0.66, -0.70, -0.62]
        comp = [0.19, 0.28, 0.11, 0.24, 0.31, 0.07, 0.22]
        result = calc(meta, comp)
        assert result.asymmetry_score == pytest.approx(-0.8885714285714286)
        assert result.t_statistic == pytest.approx(-23.2940830630946)
        assert result.p_value < 1e-6
        assert result.cohens_d == pytest.approx(-12.451211137307666)
        assert result.is_significant is True
        assert result.confidence_interval_lower == pytest.approx(
            -0.9571428571428571)
        assert result.confidence_interval_upper == pytest.approx(
            -0.8185357142857143)
        # The strong arm-swap negates the asymmetry exactly.
        swapped = calc(comp, meta)
        assert swapped.asymmetry_score == pytest.approx(0.8885714285714286)

    def test_near_null_pair_stays_silent(self):
        calc = self._calculate()
        meta = [0.04, -0.07, 0.02, -0.05, 0.09, -0.01, 0.03]
        comp = [0.06, -0.04, -0.08, 0.01, 0.05, -0.06, -0.02]
        result = calc(meta, comp)
        assert result.asymmetry_score == pytest.approx(0.01857142857142857)
        assert result.p_value > 0.05
        assert result.is_significant is False

    def test_degenerate_n1_contract(self):
        # The classic degenerate guard: n=1 per arm yields t=0.0,
        # p=1.0, d=0.0 and is_significant False regardless of the
        # illustrative pair mean (here +0.30 vs +0.05, delta +0.25).
        calc = self._calculate()
        result = calc([0.30], [0.05])
        assert result.asymmetry_score == pytest.approx(0.25)
        assert result.t_statistic == 0.0
        assert result.p_value == 1.0
        assert result.cohens_d == 0.0
        assert result.is_significant is False

    def test_engine_layer_not_finding_layer(self):
        # The m934/m935/m936 mechanisms never promote engine
        # significance to a finding: all three carry manual-only
        # discipline (m934 MANUAL ILLUSTRATIVE ONLY engine NOT run,
        # m935 MANUAL ILLUSTRATIVE ONLY, m936 tone NOT_SCORED /
        # engine NOT run).
        b934 = _m934_block()["scorer"]
        assert "MANUAL ILLUSTRATIVE ONLY" in b934["method"]
        b935 = _m935_block()["scorer"]["method"]
        assert "MANUAL ILLUSTRATIVE ONLY" in b935
        b936 = _m936_block()
        assert b936["is_significant"] is False
        assert b936["engine_run"] is False
        assert b936["tone_scored"] is False


