class TestTypeDSyntheticEngineCalibration1055:
    # FRESH synthetic corpora this run (new values, not #1050's).
    # Engine significance is never promoted to a finding: the m862 /
    # m863 / m864 mechanisms verified this run carry finding-layer
    # is_significant false / NOT asserted per the Aug 28 2026 standing
    # rule.
    STRONG_META = [-0.78, -0.82, -0.80, -0.79, -0.81, -0.80, -0.80]
    STRONG_COMP = [0.02, -0.01, 0.00, 0.01, -0.02, 0.00, 0.00]
    NULL_META = [-0.01, 0.03, -0.02, 0.00, 0.02, -0.03, 0.01]
    NULL_COMP = [0.01, -0.03, 0.02, 0.00, -0.01, 0.02, -0.05]

    def _scorer(self):
        import sys

        sys.path.insert(0, REPO_ROOT)
        from mediascope.score.statistical import (
            welch_t_test,
            cohens_d,
            bootstrap_ci,
        )

        return welch_t_test, cohens_d, bootstrap_ci

    def test_strong_signal_significant_at_engine_layer(self):
        welch_t_test, cohens_d, bootstrap_ci = self._scorer()
        a = self.STRONG_META
        b = self.STRONG_COMP
        import numpy as np

        asym = float(np.mean(a) - np.mean(b))
        t, p = welch_t_test(a, b)
        d = cohens_d(a, b)
        ci = bootstrap_ci(a, b)
        import pytest

        assert asym == pytest.approx(-0.7999999999999999, rel=1e-12)
        assert t == pytest.approx(-115.931013969515561, rel=1e-9)
        assert p == pytest.approx(1.137219895606129e-19, rel=1e-6)
        assert d == pytest.approx(-61.967733539318708, rel=1e-9)
        assert ci[0] == pytest.approx(-0.8114285714285716, rel=1e-12)
        assert ci[1] == pytest.approx(-0.7871428571428571, rel=1e-12)
        assert ci[1] < 0, "CI entirely below zero"
        assert p < 0.05

    def test_near_null_stays_silent(self):
        welch_t_test, cohens_d, bootstrap_ci = self._scorer()
        a = self.NULL_META
        b = self.NULL_COMP
        import numpy as np
        import pytest

        asym = float(np.mean(a) - np.mean(b))
        t, p = welch_t_test(a, b)
        d = cohens_d(a, b)
        ci = bootstrap_ci(a, b)
        assert asym == pytest.approx(0.0057142857142857, rel=1e-9)
        assert t == pytest.approx(0.443532762572744, rel=1e-9)
        assert p == pytest.approx(0.665572484286263, rel=1e-9)
        assert d == pytest.approx(0.237078233908080, rel=1e-9)
        assert ci[0] == pytest.approx(-0.0171428571428571, rel=1e-9)
        assert ci[1] == pytest.approx(0.0300000000000000, rel=1e-9)
        assert ci[0] < 0 < ci[1], "CI crosses zero"
        assert p >= 0.05, "near-null pair stays silent"

    def test_degenerate_n1_guard_on_m862_pair(self):
        # Degenerate n=1-per-arm contract on the m862 illustrative
        # pair ([-0.35] OpenAI, [-0.50] Meta): the classic guard.
        welch_t_test, cohens_d, _ = self._scorer()
        import numpy as np
        import pytest

        openai_arm = [-0.35]
        meta_arm = [-0.50]
        t, p = welch_t_test(openai_arm, meta_arm)
        d = cohens_d(openai_arm, meta_arm)
        assert abs(float(np.mean(openai_arm) - np.mean(meta_arm))) == pytest.approx(
            0.15, abs=1e-12
        )
        assert t == 0.0
        assert p == 1.0
        assert d == 0.0
        # Arm-swap negates the signed asymmetry.
        t2, _ = welch_t_test(meta_arm, openai_arm)
        assert t2 == 0.0
        assert float(np.mean(meta_arm) - np.mean(openai_arm)) == pytest.approx(
            -0.15, abs=1e-12
        )


