class TestSarahPerezThreeEntityGradient(unittest.TestCase):
    """Validates the three-entity cross-journalist natural experiment."""

    def test_google_article_neutral_aspirational(self):
        """Google AI glasses article uses aspirational framing with zero privacy alarm."""
        article = {
            "url": "https://techcrunch.com/2026/05/22/we-tried-googles-ai-glasses-and-theyre-almost-there/",
            "date": "2026-05-22",
            "author": "Sarah Perez",
            "entity": "Google",
            "title": "We tried Google's AI glasses and they're almost there",
        }
        assert article["author"] == "Sarah Perez"
        assert "almost there" in article["title"]  # Aspirational
        # No alarm vocabulary in title
        for word in ["creepy", "surveillance", "privacy", "pervert", "spy", "fear"]:
            assert word not in article["title"].lower()

    def test_meta_article_adversarial(self):
        """Meta AI glasses article uses adversarial framing with alarm vocabulary."""
        article = {
            "url": "https://techcrunch.com/2026/07/08/meta-wants-its-ai-glasses-to-seem-less-creepy-its-ai-strategy-says-otherwise/",
            "date": "2026-07-08",
            "author": "Sarah Perez",
            "entity": "Meta",
            "title": "Meta wants its AI glasses to seem less creepy. Its AI strategy says otherwise.",
        }
        assert article["author"] == "Sarah Perez"
        assert "creepy" in article["title"].lower()  # Alarm vocabulary in title
        # Title structure is accusatory: "wants to seem X. strategy says otherwise."
        assert "says otherwise" in article["title"]  # Contradiction framing

    def test_apple_article_defensive_protective(self):
        """Apple camera AirPods article uses defensive/protective framing."""
        article = {
            "url": "https://techcrunch.com/2026/08/18/why-apples-camera-equipped-airpods-may-not-be-the-pervert-pods-consumers-fear/",
            "date": "2026-08-18",
            "author": "Sarah Perez",
            "entity": "Apple",
            "title": "Why Apple's camera-equipped AirPods may not be the 'pervert pods' consumers fear",
        }
        assert article["author"] == "Sarah Perez"
        # Defensive language: "may not be" + scare-quoted "pervert pods"
        assert "may not be" in article["title"]  # Protective
        assert "'pervert pods'" in article["title"]  # Scare quotes — distancing
        # Title DEFENDS Apple: why they are NOT the bad thing
        assert article["title"].startswith("Why Apple")  # Explanatory defense

    def test_three_entity_same_journalist(self):
        """All three articles are by the same journalist: Sarah Perez."""
        articles = [
            {"entity": "Google", "date": "2026-05-22", "author": "Sarah Perez"},
            {"entity": "Meta", "date": "2026-07-08", "author": "Sarah Perez"},
            {"entity": "Apple", "date": "2026-08-18", "author": "Sarah Perez"},
        ]
        authors = {a["author"] for a in articles}
        assert len(authors) == 1, f"Expected 1 author, got {authors}"
        assert "Sarah Perez" in authors

    def test_three_entity_within_88_days(self):
        """All three articles published within an 88-day window."""
        from datetime import datetime

        dates = [
            datetime(2026, 5, 22),  # Google
            datetime(2026, 7, 8),  # Meta
            datetime(2026, 8, 18),  # Apple
        ]
        span = (dates[-1] - dates[0]).days
        assert span == 88, f"Expected 88-day span, got {span}"

    def test_title_sentiment_gradient(self):
        """Titles form a gradient: aspirational (Google) → adversarial (Meta) → defensive (Apple)."""
        titles = {
            "google": "We tried Google's AI glasses and they're almost there",
            "meta": "Meta wants its AI glasses to seem less creepy. Its AI strategy says otherwise.",
            "apple": "Why Apple's camera-equipped AirPods may not be the 'pervert pods' consumers fear",
        }
        # Google: positive framing markers
        assert "almost there" in titles["google"]  # Positive anticipation
        assert "creepy" not in titles["google"].lower()

        # Meta: negative framing markers
        assert "creepy" in titles["meta"].lower()  # Alarm vocabulary
        assert "otherwise" in titles["meta"]  # Contradiction/accusation

