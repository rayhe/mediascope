class TestStalenessPins:
    def _class_run(self, filename, classname):
        target = os.path.join(TESTS_DIR, filename)
        env = dict(os.environ)
        env["PYTEST_DISABLE_PLUGIN_AUTOLOAD"] = "1"
        res = subprocess.run(
            ["python3", "-m", "pytest", target,
             "-k", classname,
             "-q", "--no-header"],
            cwd=REPO_ROOT, capture_output=True, text=True, env=env,
        )
        return res

    def test_1190_guard_lifecycle_still_green(self):
        # The #1190 Type D file's guard-lifecycle class pins max id 945
        # and the zero next-number nine-four-six forward guards
        # (numeric), the direction/member guards (thirty-fifth through
        # thirty-eighth landed; thirty-ninth direction absent;
        # forty-seventh and forty-eighth member-claims absent). FOUR of
        # the five pass: this Type E run lands no mechanisms.
        # PINNED NOT REPAIRED: the fifth,
        # test_no_type_a_1191_in_git_log_pin, fails BY DESIGN because
        # the #1190 main commit's own message BODY names "Type A
        # #1191" as the next leg (body line 11: "no Type D #1190 / no
        # Type A #1191 in git log"), so git log --grep="Type A #1191"
        # (which matches against full commit messages, not subjects
        # only) matches the #1190 commit itself. The pin's needle is
        # self-tripping; the "no-Type-A-#1191" forward guard therefore
        # cannot be verified with this grep form, and no Type A #1191
        # COMMIT exists (the matches are the #1190 body text only).
        # Recorded here, not repaired (Type D committed block is
        # read-only to this run); a future non-Type-D run reconciles
        # the grep form.
        res = self._class_run(
            D1190_FILE,
            "TestGuardLifecycle1190",
        )
        assert res.returncode != 0, res.stdout[-2000:]
        assert (
            "1 failed, 4 passed" in res.stdout
        ), res.stdout[-2000:]
