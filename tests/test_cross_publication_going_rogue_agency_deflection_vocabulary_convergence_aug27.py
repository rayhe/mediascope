class TestAgencyAttributionAsymmetry:
    """Test the grammatical subject asymmetry between OpenAI and Meta coverage."""

    # OpenAI coverage: MODEL/AGENT as grammatical subject
    OPENAI_SUBJECT_FRAMES = {
        'reuters_report': {
            'headline': "OpenAI report says its network was hacked by its own rogue AI agents",
            'subject': 'rogue AI agents',
            'verb': 'hacked',
            'company_role': 'reporter (OpenAI report says...)',
        },
        'reuters_metr': {
            'text': "about 700 AI agents spun up by the company OpenAI participated in breach",
            'subject': 'AI agents',
            'verb': 'participated',
            'company_role': 'passive qualifier (spun up by)',
        },
        'wsj': {
            'headline': "AI Just Went Rogue Again. This Time It Turned to Deception.",
            'subject': 'AI',
            'verb': 'Went Rogue / Turned',
            'company_role': 'absent from headline',
        },
        'verge': {
            'headline': "OpenAI's rogue AI model incident was worse than we thought",
            'subject': 'rogue AI model',
            'verb': 'broke out, figured out, hacked into',
            'company_role': "possessive qualifier (OpenAI's)",
        },
    }

    # Meta coverage: COMPANY as grammatical subject
    META_SUBJECT_FRAMES = {
        'reuters': {
            'text': "Meta designed those social media platforms to addict children",
            'subject': 'Meta',
            'verb': 'designed',
        },
        'cnn': {
            'text': "Meta...intentionally designed addictive platforms that harmed young people",
            'subject': 'Meta',
            'verb': 'intentionally designed',
        },
        'techcrunch': {
            'text': "allegations that it intentionally designed its platforms to keep children hooked",
            'subject': 'it [Meta]',
            'verb': 'intentionally designed',
        },
        'le_monde': {
            'text': "accused...of misleading consumers...allowing children under 13 to register",
            'subject': 'Meta [accused]',
            'verb': 'misleading, allowing',
        },
    }

    def test_openai_coverage_uses_model_as_subject(self):
        """In OpenAI coverage, the AI model/agent is the grammatical actor."""
        model_subjects = [
            f for f in self.OPENAI_SUBJECT_FRAMES.values()
            if 'agent' in f['subject'].lower() or 'model' in f['subject'].lower()
               or f['subject'].lower() == 'ai'
        ]
        assert len(model_subjects) == len(self.OPENAI_SUBJECT_FRAMES), \
            "All OpenAI coverage should use model/agent as subject"

    def test_meta_coverage_uses_company_as_subject(self):
        """In Meta coverage, the company is the grammatical actor."""
        company_subjects = [
            f for f in self.META_SUBJECT_FRAMES.values()
            if 'meta' in f['subject'].lower() or 'it' in f['subject'].lower()
        ]
        assert len(company_subjects) == len(self.META_SUBJECT_FRAMES), \
            "All Meta coverage should use company as subject"

    def test_no_meta_coverage_uses_rogue_framing(self):
        """No publication described Meta's technology as 'going rogue'."""
        meta_rogue = [
            f for f in self.META_SUBJECT_FRAMES.values()
            if 'rogue' in f['text'].lower()
        ]
        assert len(meta_rogue) == 0, \
            "No publication should frame Meta technology as 'going rogue'"

    def test_openai_company_role_is_passive(self):
        """In OpenAI coverage, the company is positioned as respondent, not perpetrator."""
        passive_roles = [
            f for f in self.OPENAI_SUBJECT_FRAMES.values()
            if any(term in f['company_role'].lower()
                   for term in ['reporter', 'qualifier', 'absent', 'passive', 'possessive'])
        ]
        assert len(passive_roles) == len(self.OPENAI_SUBJECT_FRAMES), \
            "OpenAI's corporate role should be passive across all examples"


