class TestStalenessPins1276:
    def _class_run(self, filename, classname):
        target = os.path.join(TESTS_DIR, filename)
        env = dict(os.environ)
        env["PYTEST_DISABLE_PLUGIN_AUTOLOAD"] = "1"
        res = subprocess.run(
            ["python3", "-m", "pytest", target,
             "-k", classname,
             "-q", "--no-header"],
            cwd=REPO_ROOT, capture_output=True, text=True, env=env,
        )
        return res

    def test_1275_guard_lifecycle_post_commit(self):
        # Post-main-commit form: 17 tests in the class, 16 pass and 1
        # fails - the no_type_d_1275_in_git_log pin. CRITICAL
        # NUANCE vs the usual #1191-class self-trip: this pin was
        # ALREADY red pre-commit at #1276 (tripped by #1275's own main
        # commit, whose subject carries "Type D #1275"; pinned by
        # TestStalenessPins1275 as #1275's self-trip). It does NOT
        # flip at #1276's main commit. And NO no-Type-E-#1276-in-git-log
        # pin exists in TestGuardLifecycle1275 to flip (the #1275
        # iteration-log entry's forward-guard prose claims one was
        # laid; the code lays test_no_type_d_1275_in_git_log_pin
        # instead - a prose/code discrepancy, documented here, not
        # repaired; #1275's file is read-only to this run). The class
        # run below therefore expects the same "1 failed, 16 passed"
        # both pre- and post-commit, with the failing pin named.
        res = self._class_run(
            D1275_FILE,
            "TestGuardLifecycle1275",
        )
