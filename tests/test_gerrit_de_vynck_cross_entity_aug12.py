        notes = str(wapo_entry.get("notes", "")).lower()
        combined = beat + notes
        self.assertTrue(
            "google" in combined or "alphabet" in combined or "ai" in combined,
            "WaPo entry should mention Google/Alphabet or AI beat"
        )


