def _load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


def _get_mechanism(data, mechanism_id):
    """Find mechanism by ID in cross_publication_findings (dict of named entries)."""
    findings = data.get("cross_publication_findings", {})
    if isinstance(findings, dict):
        for key, entry in findings.items():
            if isinstance(entry, dict) and entry.get("mechanism_id") == mechanism_id:
                return entry
    elif isinstance(findings, list):
        for entry in findings:
            if isinstance(entry, dict) and entry.get("mechanism_id") == mechanism_id:
                return entry
    return None


def _get_journalist(data, name):
    """Find journalist by name in journalists.yaml."""
    journalists = data.get("journalists", data) if isinstance(data, dict) else data
    if isinstance(journalists, list):
        for j in journalists:
            if isinstance(j, dict) and j.get("name") == name:
                return j
    return None


