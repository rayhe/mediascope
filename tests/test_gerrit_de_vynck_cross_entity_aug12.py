        """WaPo hiring announcement specified Google/Alphabet focus."""
        career = self.journalist.get("career", [])
        wapo_entry = None
        for c in career:
            pub = c.get("publication", "")
            if "washington-post" in pub.lower() or "wapo" in pub.lower():
                wapo_entry = c
                break
        self.assertIsNotNone(wapo_entry)
        # Check that the initial beat or notes mention Google
