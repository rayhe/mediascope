        def find_mechanism(obj, mech_id):
            if isinstance(obj, dict):
                if obj.get('mechanism_id') == mech_id:
                    return obj
                for v in obj.values():
                    result = find_mechanism(v, mech_id)
                    if result:
                        return result
            elif isinstance(obj, list):
                for item in obj:
                    result = find_mechanism(item, mech_id)
                    if result:
                        return result
            return None

        mech = find_mechanism(research, 140)
        assert mech is not None
        urls = mech.get('source_urls', [])
        has_ownership = any('simplywall' in u or 'marketbeat' in u or 'insidermonkey' in u
                           for u in urls)
        assert has_ownership, "Must cite institutional ownership data source"
