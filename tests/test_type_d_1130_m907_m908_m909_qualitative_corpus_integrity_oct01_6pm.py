class TestSyntheticEngineCalibration1130:
    # Scratch-run values produced at this run (Thu 2026-10-01 ~18:05
    # PDT) via mediascope.score.asymmetry.calculate_asymmetry with
    # its real signature (target_scores, peer_scores,
    # target_entity, peer_entities, publication_slug,
    # period_start, period_end). The finding layer stays MANUAL
    # ILLUSTRATIVE ONLY: the engine is never promoted to findings,
    # and these numbers are NOT a corpus claim.

    def _calculate(self):
        from datetime import datetime

        from mediascope.score.asymmetry import calculate_asymmetry

        def calc(target_scores, peer_scores):
            return calculate_asymmetry(
                target_scores,
                peer_scores,
                "Meta",
                ["Anthropic", "OpenAI"],
                "synthetic-calibration",
                datetime(2026, 10, 1),
                datetime(2026, 10, 1),
            )

        return calc

    def test_strong_effect_is_significant(self):
        calc = self._calculate()
        meta = [-0.69, -0.55, -0.62, -0.71, -0.58, -0.66, -0.60, -0.64]
        comp = [0.18, -0.05, 0.22, 0.09, -0.11, 0.14, -0.03, 0.08]
        result = calc(meta, comp)
        assert result.asymmetry_score == pytest.approx(-0.69625)
        assert result.t_statistic == pytest.approx(-15.200693087048057)
        assert result.p_value < 1e-7
        assert result.cohens_d == pytest.approx(-7.6003465435240285)
        assert result.is_significant is True
        # The strong arm-swap negates the asymmetry exactly.
        swapped = calc(comp, meta)
        assert swapped.asymmetry_score == pytest.approx(0.69625)

    def test_near_null_pair_stays_silent(self):
        calc = self._calculate()
        meta = [-0.10, -0.02, -0.06, -0.12, -0.04, -0.08, -0.05, -0.09]
        comp = [-0.03, -0.07, 0.01, -0.05, -0.09, -0.02, -0.06, 0.00]
        result = calc(meta, comp)
        assert result.asymmetry_score == pytest.approx(-0.03125)
        assert result.p_value > 0.05
        assert result.is_significant is False

    def test_degenerate_n1_contract(self):
        # The classic degenerate guard: n=1 per arm yields t=0.0,
        # p=1.0, d=0.0 and is_significant False regardless of the
        # illustrative pair mean.
        calc = self._calculate()
        result = calc([-0.40], [-0.55])
        assert result.asymmetry_score == pytest.approx(0.15)
        assert result.t_statistic == 0.0
        assert result.p_value == 1.0
        assert result.cohens_d == 0.0
        assert result.is_significant is False

    def test_engine_layer_not_finding_layer(self):
        # The m907/m908/m909 mechanisms never promote engine
        # significance to a finding: all three carry finding-layer
        # is_significant False (or tone NOT_SCORED for the Type C).
        with open(VERGE_FILE) as f:
            b907 = yaml.safe_load(f)["competitor_relationships"]["openai"][KEY_907]
        assert "is_significant: false" in b907["statistical_discipline"]
        with open(JOURNALISTS_FILE) as f:
            b908 = yaml.safe_load(f)["david_heaney"]["competitor_coverage"][KEY_908]
        assert "is_significant False" in b908["scorer"]["method"] or \
            "is_significant" in str(b908)
        with open(ENTITIES_FILE) as f:
            b909 = yaml.safe_load(f)[KEY_909]
        assert b909["is_significant"] is False
        assert b909["engine_run"] is False


