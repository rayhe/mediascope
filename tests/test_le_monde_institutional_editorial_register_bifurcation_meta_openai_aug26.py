        openai_teen_register = "a voir"     # wait and see re: ChatGPT 13-17 version
        # Both terms appear in the SAME Meta editorial document
        assert meta_teen_register != openai_teen_register, (
            "Same editorial applies different registers to identical teen-AI question"
        )


