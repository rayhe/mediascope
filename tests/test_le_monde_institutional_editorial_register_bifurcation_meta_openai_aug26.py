class TestEditorialRegisterAsymmetry:
    """Measure vocabulary register differences between Meta and OpenAI coverage."""

    # Vocabulary extracted from fetched article text (Aug 26 observation)
    META_EDITORIAL_VOCABULARY = {
        "alarm_register": [
            "avidite",                    # greed (in headline)
            "addiction des adolescents",   # teen addiction
            "dissimuler la nocivite",      # conceal harmfulness
            "depression",                 # depression
            "illegalement",               # illegally
            "accablants",                 # damning
            "fardeau societal commun",    # common societal burden
            "cigarettiers",              # tobacco companies
            "mepris de l'ethique",        # contempt for ethics
            "clients speciaux",           # "special" customers (10-12 yr olds)
        ],
        "neutral_terms": [
            "reseaux sociaux",            # social media (descriptive)
        ]
    }

    OPENAI_ARTICLE_VOCABULARY = {
        "alarm_register": [],              # ZERO alarm-register terms
        "neutral_or_sympathetic": [
            "enjeu crucial",               # crucial challenge
            "confiance",                   # trust
            "sensible",                    # sensitive
            "objectifs ambitieux",          # ambitious targets
            "se distinguer",              # distinguish itself
            "environnement publicitaire conversationnel",  # conversational ad environment
            "defi",                        # challenge
        ],
        "openai_pr_language_relayed": [
            "clairement identifiees et separees",  # clearly identified and separated
            "n'influencent pas ces reponses",      # do not influence responses
            "les utilisateurs gardent le controle",  # users remain in control
            "intention commerciale claire",         # clear commercial intent
        ]
    }

    def test_meta_alarm_vocabulary_count(self):
        """Meta editorial uses 10+ alarm-register terms."""
        alarm_count = len(self.META_EDITORIAL_VOCABULARY["alarm_register"])
        assert alarm_count >= 10, f"Expected 10+ alarm terms, got {alarm_count}"

    def test_openai_alarm_vocabulary_count(self):
        """OpenAI article uses ZERO alarm-register terms."""
        alarm_count = len(self.OPENAI_ARTICLE_VOCABULARY["alarm_register"])
        assert alarm_count == 0, f"Expected 0 alarm terms, got {alarm_count}"

    def test_vocabulary_register_asymmetry_ratio(self):
        """Alarm vocabulary ratio is infinite (10:0) -- Meta vs OpenAI."""
        meta_alarm = len(self.META_EDITORIAL_VOCABULARY["alarm_register"])
        openai_alarm = len(self.OPENAI_ARTICLE_VOCABULARY["alarm_register"])
        assert meta_alarm > 0 and openai_alarm == 0, (
            "Asymmetry must be complete: Meta gets alarm register, "
            "OpenAI gets zero alarm terms"
        )

    def test_openai_pr_language_relay(self):
        """OpenAI article relays 4+ OpenAI PR claims without editorial challenge."""
        relayed = len(self.OPENAI_ARTICLE_VOCABULARY["openai_pr_language_relayed"])
        assert relayed >= 4, f"Expected 4+ unchallenged PR relays, got {relayed}"

    def test_tobacco_comparison_applied_only_to_meta(self):
        """Tobacco industry comparison deployed for Meta, not for OpenAI."""
        meta_has_tobacco = "cigarettiers" in self.META_EDITORIAL_VOCABULARY["alarm_register"]
        openai_has_tobacco = any(
            "tabac" in t or "cigarett" in t
            for t in (self.OPENAI_ARTICLE_VOCABULARY["alarm_register"]
                      + self.OPENAI_ARTICLE_VOCABULARY["neutral_or_sympathetic"])
        )
        assert meta_has_tobacco is True, "Meta editorial must invoke tobacco comparison"
        assert openai_has_tobacco is False, "OpenAI article must NOT invoke tobacco comparison"

    def test_a_voir_vs_accablants_teen_coverage(self):
        """Same editorial uses 'a voir' (wait and see) for ChatGPT teens but
        'accablants' (damning) for Meta teens -- register inversion within
        a single document."""
