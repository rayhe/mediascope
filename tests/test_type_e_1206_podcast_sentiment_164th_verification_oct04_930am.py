def _tracked_grep_files(needle):
    """Return tracked files containing a literal needle (repo-wide).

    Note the argument order: the needle comes before the revision
    (no stray "--" ahead of the needle - the #1171 in-gate lesson:
    a "--" before the needle makes git grep treat the needle as a
    pathspec, which silently returns zero hits and makes negative
    guards pass vacuously).
    """
    out = _git("grep", "-F", "-l", needle, "HEAD", "--", ".").stdout
    return [l for l in out.splitlines() if l.strip()]


