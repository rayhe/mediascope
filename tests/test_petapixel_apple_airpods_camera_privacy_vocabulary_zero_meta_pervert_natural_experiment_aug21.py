def find_mechanism_anywhere(mechanism_id):
    """Search all YAML sections for a mechanism by ID."""
    yaml_path = os.path.join(
        os.path.dirname(__file__), '..', 'profiles', 'competitor-coverage-research.yaml'
    )
    with open(yaml_path, 'r') as f:
        data = yaml.safe_load(f)

    # Recursive search for any dict with matching mechanism_id
    def _search(obj):
        if isinstance(obj, dict):
            if obj.get('mechanism_id') == mechanism_id:
                return obj
            for v in obj.values():
                result = _search(v)
                if result is not None:
                    return result
        elif isinstance(obj, list):
            for item in obj:
                result = _search(item)
                if result is not None:
                    return result
        return None

    return _search(data)


