class TestCompetitorCEOSourceAmplification:
    """Core mechanism: Spiegel's competitive rhetoric is cited with attribution
    but without competitive incentive context, then amplified editorially."""

    def test_spiegel_cited_as_authority_not_competitor(self):
        """Article cites Spiegel as 'recently noted' — authority verb,
        not 'claimed' or 'alleged' or 'argued' (competitive verbs)."""
        pero_attribution = "As Snap CEO Evan Spiegel recently noted"
        assert "noted" in pero_attribution  # authority/factual verb
        # Competitive attribution verbs that WOULD signal bias:
        competitive_verbs = ["claimed", "alleged", "argued", "asserted",
                             "contended", "complained"]
        for verb in competitive_verbs:
            assert verb not in pero_attribution, (
                f"Pero uses authority verb 'noted', not competitive verb '{verb}'"
            )

    def test_competitive_incentive_absent(self):
        """Article does not mention that Snap is Meta's direct competitor
        in camera-equipped smart glasses."""
        # The article mentions Spiegel is "Snap CEO" but never notes:
        competitive_context_elements = [
            "Snap Specs",  # Snap's competing product
            "competing glasses",
            "rival product",
            "Snap's own smart glasses",
            "competing camera glasses",
            "commercial interest",
            "financial incentive"
        ]
        # Full article text does not contain any of these contextual notes
        article_text = (
            "As Snap CEO Evan Spiegel recently noted, the partnership between "
            "Meta and EssilorLuxottica has mostly benefited Meta. Ray-Ban-branded "
            "glasses might be good for sweeping Meta's name under the rug, but "
            "it's also made Ray-Bans synonymous with poor privacy practices and "
            "have gutted margins on the company's non-smart Ray-Bans. Maybe "
            "Google will fare better on the reputation front, but given its "
            "history of hoovering up user data and the fact it was the company "
            "responsible for spawning the word 'Glasshole,' I won't be holding "
            "my breath."
        )
        for element in competitive_context_elements:
            assert element.lower() not in article_text.lower(), (
                f"Competitive context '{element}' absent from article — "
                "Spiegel's commercial incentive is not disclosed"
            )

    def test_spiegel_said_camouflage_pero_wrote_poor_privacy(self):
        """Spiegel said 'camouflage their brand' — Pero extended to
        'synonymous with poor privacy practices' (stronger claim)."""
        spiegel_actual = "Meta needs to camouflage their brand"
        pero_extension = "made Ray-Bans synonymous with poor privacy practices"
        # Spiegel's framing: brand perception / aesthetics
        assert "camouflage" in spiegel_actual
        assert "privacy" not in spiegel_actual  # Spiegel didn't say this
        # Pero's extension: privacy reputation (more specific, more damaging)
        assert "poor privacy practices" in pero_extension
        # The extension adds a privacy-specific claim Spiegel didn't make

    def test_spiegel_said_destroyed_margin_pero_wrote_gutted(self):
        """Spiegel said 'destroyed the margin' — Pero wrote 'gutted margins'
        and extended to non-smart Ray-Bans specifically."""
        spiegel_actual = "they destroyed the margin"
        pero_version = "gutted margins on the company's non-smart Ray-Bans"
        # Spiegel discussed margin destruction on META-BRANDED Ray-Bans
        assert "non-smart" not in spiegel_actual
        # Pero extends to claim it hurt ALL Ray-Ban products
        assert "non-smart Ray-Bans" in pero_version

    def test_attribution_blending_ambiguity(self):
        """The paragraph structure makes it unclear where Spiegel's claims
        end and Pero's editorial analysis begins."""
        # Full paragraph from article:
        paragraph = (
            "As Snap CEO Evan Spiegel recently noted, the partnership between "
            "Meta and EssilorLuxottica has mostly benefited Meta. Ray-Ban-branded "
            "glasses might be good for sweeping Meta's name under the rug, but "
            "it's also made Ray-Bans synonymous with poor privacy practices and "
            "have gutted margins on the company's non-smart Ray-Bans."
        )
        # Sentence 1: Attributed to Spiegel ("As... Spiegel noted")
        sentences = paragraph.split(". ")
        assert "Spiegel" in sentences[0]
        # Sentence 2: No attribution — reads as editorial analysis
        # but follows directly from Spiegel attribution, creating ambiguity
        assert "Spiegel" not in sentences[1]
        assert "Ray-Ban-branded glasses" in sentences[1]
        # Reader cannot determine if sentence 2 is Spiegel's claim or Pero's


class TestThreeEntityFashionPartnershipFraming:
    """Same-article framing of three entities pursuing IDENTICAL fashion
    partnership strategies for camera-equipped smart glasses."""

    def test_google_gucci_aspirational_vocabulary(self):
        """Google's Gucci partnership described with aspirational language."""
        google_terms = ["level up", "cachet", "bougier", "premium"]
        article_text = (
            "Google will enlist its own EssilorLuxottica in a bid to level up "
            "its incoming smart glasses' cachet. While the strategy is similar "
            "to Meta's, it's also a bit bougier."
        )
        found = [t for t in google_terms if t in article_text]
        assert len(found) >= 2, (
            f"Google gets aspirational vocabulary: {found}"
        )

    def test_apple_hermes_positive_precedent(self):
        """Apple's Hermès partnership treated as successful, established precedent."""
        apple_text = (
            "In some ways, it's just as much a piece of the Meta playbook as "
            "it is Apple's. Since 2015, Apple has been selling an Apple Watch "
            "with Hermès branding at price points above $1,000."
        )
        # Apple's luxury partnership: established, successful, no privacy concern
        assert "Apple's" in apple_text
        assert "Hermès" in apple_text
        assert "privacy" not in apple_text.lower()
        assert "reputation" not in apple_text.lower()

    def test_meta_prada_reputation_dismissal(self):
        """Meta's Prada partnership dismissed as impossible due to reputation damage."""
        meta_text = (
            "Whether anyone wants luxury smart glasses is an open question, but "
            "rumors have suggested that Meta might be considering a similar "
            "partnership with Prada, a fashion brand that, like Gucci, is also "
            "solidly in the luxury space. Those rumors have obviously yet to "
            "materialize, though, and with the way things are going with Meta's "
            "reputation in the smart glasses world, maybe they never will."
        )
        # Meta gets reputation-damage framing
        assert "reputation" in meta_text
        assert "maybe they never will" in meta_text
        # Dismissive tone: Meta's identical strategy declared DOA
        assert "obviously" in meta_text  # editorial certainty

    def test_identical_strategy_different_editorial_evaluation(self):
        """All three entities pursue the SAME strategy: luxury brand partnership
        for camera-equipped smart glasses. Only editorial evaluation differs."""
        strategies = {
            "Google": {"partner": "Gucci", "frame": "aspirational",
                       "vocab": ["level up", "cachet"]},
            "Apple": {"partner": "Hermès", "frame": "precedent",
                      "vocab": ["established", "since 2015"]},
            "Meta": {"partner": "Prada/Ray-Ban", "frame": "dismissed",
                     "vocab": ["reputation", "maybe never"]},
        }
        # All three do the same thing: partner with fashion brand for tech glasses
        for entity in strategies:
            assert strategies[entity]["partner"] is not None
        # But framing is completely different
        frames = {s["frame"] for s in strategies.values()}
        assert len(frames) == 3, "Three entities, three different frames"


