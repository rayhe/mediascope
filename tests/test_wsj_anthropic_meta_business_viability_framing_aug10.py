        anthropic_revenue_b = 47
        meta_profitable = True
        anthropic_profitable = False

        # Financial health: Meta > Anthropic
        assert meta_revenue_b > anthropic_revenue_b
        assert meta_profitable and not anthropic_profitable

        # Framing valence: Meta gets negative, Anthropic gets positive
        meta_framing = "deficit"
        anthropic_framing = "celebration"
        assert meta_framing != anthropic_framing  # Inverse correlation


