# Class 8: Legitimate Factors — Confounders Documented
# =============================================================================
class TestLegitimateFactors:
    """Document confounders that could explain the asymmetry without
    financial incentive."""

    LEGITIMATE_FACTORS = [
        {
            "factor": "Ad concentration is real risk",
            "explanation": "Meta's 97.6% ad revenue dependency IS a genuine concentration risk worthy of analysis",
            "weakened_by": "But Anthropic's 0% profit and $27B burn is a MORE severe risk by most financial metrics",
        },
        {
            "factor": "Column format difference",
            "explanation": "Heard on the Street is opinion/analysis; investor profile is feature writing",
            "weakened_by": "But the ABSENCE of a Heard on the Street column for Anthropic's risks is the finding",
        },
        {
            "factor": "Model quality gap",
            "explanation": "Meta's models DO trail Anthropic/OpenAI on benchmarks — follower framing has factual basis",
            "weakened_by": "But embedding follower framing in a policy essay article (not a model review) is editorial choice",
        },
        {
            "factor": "Chinese walls",
            "explanation": "News Corp editorial is nominally independent of business operations",
            "weakened_by": "Chinese walls are procedural, not empirical — the framing pattern exists regardless of intent",
        },
        {
            "factor": "Anthropic growth is impressive",
            "explanation": "Anthropic's revenue growth ($47B ARR) IS objectively impressive",
            "weakened_by": "Meta's revenue ($244B) is 5x larger and profitable — growth without profit is a standard risk flag",
        },
        {
            "factor": "WSJ best-in-class disclosure",
            "explanation": "WSJ discloses financial relationships more than any other profiled publication",
            "weakened_by": "Disclosure doesn't prevent framing asymmetry — it addresses transparency, not bias",
        },
    ]

    @pytest.mark.parametrize("factor", [f["factor"] for f in LEGITIMATE_FACTORS])
    def test_legitimate_factor_has_counterpoint(self, factor):
        """Every legitimate factor should also have a documented counterpoint."""
        matching = [f for f in self.LEGITIMATE_FACTORS if f["factor"] == factor]
        assert len(matching) == 1
        assert matching[0].get("weakened_by"), \
            f"Legitimate factor '{factor}' must have a documented counterpoint"

    def test_sufficient_legitimate_factors(self):
        """At least 5 legitimate factors documented."""
        assert len(self.LEGITIMATE_FACTORS) >= 5

    def test_strongest_confounder_identified(self):
        """The strongest confounder — ad concentration risk — should be
        first and clearly stated."""
        strongest = self.LEGITIMATE_FACTORS[0]
        assert "concentration" in strongest["factor"].lower() or \
               "ad" in strongest["factor"].lower()
