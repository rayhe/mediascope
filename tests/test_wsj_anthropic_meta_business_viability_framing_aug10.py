class TestCrossEntityFramingRegisters:
    """Compare the editorial registers WSJ uses for Meta vs Anthropic
    business coverage."""

    META_LOADED_WORDS = [
        "exposes", "weak hand", "badly needs", "don't look great",
        "little progress", "over its skis", "one-track", "late entrant",
        "struggle", "far-fetched", "too little too late",
        "lagging behind", "catch up", "impatient", "selloff",
    ]

    ANTHROPIC_LOADED_WORDS = [
        "home run", "new way to win", "elevated",
        "most money ever raised", "racing to resolve",
    ]

    def test_meta_negative_word_density(self):
        """Meta business coverage uses significantly more negative-loaded
        language than Anthropic business coverage."""
        meta_negative = [w for w in self.META_LOADED_WORDS if any(
            neg in w for neg in ["weak", "badly", "struggle", "little", "late",
                                  "far-fetched", "lag", "impatient", "selloff",
                                  "over its skis", "don't look"]
        )]
        anthropic_negative = [w for w in self.ANTHROPIC_LOADED_WORDS if any(
            neg in w for neg in ["weak", "badly", "struggle", "little", "late",
                                  "far-fetched", "lag", "impatient", "selloff"]
        )]
        assert len(meta_negative) > len(anthropic_negative), \
            f"Meta negative: {len(meta_negative)}, Anthropic negative: {len(anthropic_negative)}"

    def test_anthropic_positive_word_density(self):
        """Anthropic business coverage uses more positive-loaded language."""
        anthropic_positive = [w for w in self.ANTHROPIC_LOADED_WORDS if any(
            pos in w for pos in ["win", "home run", "elevated", "most money",
                                  "racing", "resolve"]
        )]
        meta_positive = [w for w in self.META_LOADED_WORDS if any(
            pos in w for pos in ["win", "home run", "elevated", "most money"]
        )]
        assert len(anthropic_positive) > len(meta_positive), \
            f"Anthropic positive: {len(anthropic_positive)}, Meta positive: {len(meta_positive)}"

    def test_register_inversion_vs_financial_reality(self):
        """The framing register is INVERSELY correlated with financial health:
        the healthier company (Meta) gets deficit framing, while the riskier
        company (Anthropic) gets celebration framing."""
